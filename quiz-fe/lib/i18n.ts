export function useLocale() {
  const [language, setLanguage] = useState<"vi" | "en">("vi");
  useEffect(() => {
    const update = () => setLanguage(localStorage.getItem("quiz-language") === "en" ? "en" : "vi");
    update();
    window.addEventListener("quiz-language-change", update);
    window.addEventListener("storage", update);
    return () => {
      window.removeEventListener("quiz-language-change", update);
      window.removeEventListener("storage", update);
    };
  }, []);
  return language;
}

export function useTranslation() {
  const language = useLocale();
  return useCallback((text: string) => language === "en" ? english[text] ?? text : text, [language]);
}

export function applyLanguage(language: "vi" | "en") {
  localStorage.setItem("quiz-language", language);
  document.documentElement.lang = language;
  window.dispatchEvent(new Event("quiz-language-change"));
}
